// .unfold/map.md: the map as plain Markdown for AI coding agents (and humans in a terminal).
// No code is copied in: the agent has the repo. It gets the structure the diff hides:
// which functions changed, in what order to read them, who calls whom across files, what to check.

function toAgentMarkdown(data) {
  const m = data.meta || {};
  const files = data.files.filter((f) => f.nodes.length);
  const label = (n) => (n.kind === 'top' ? 'top-level code' : (n.cls ? `${n.cls}.` : '') + n.name);
  const where = (f, n) => `${f.file}:${n.start}-${n.end}`;
  const nodeOf = (end) => {
    const f = data.files.find((x) => x.file === end.file);
    return f && { f, n: f.nodes.find((x) => x.id === end.id) };
  };
  const out = [];
  const range = m.head === 'working tree' ? `${m.base} → uncommitted changes` : `${m.base} → ${m.head}${m.headSha ? ` (${m.headSha})` : ''}`;
  out.push(`# Unfold map: ${m.subject || range}`, '');
  out.push(`Range: ${range}. Line numbers refer to the head side. Generated by \`unfold\`; rerun after changing code.`, '');
  const changedFns = files.reduce((a, f) => a + f.nodes.filter((n) => n.kind === 'fn' && n.changed).length, 0);
  out.push(`${m.changedFiles ?? files.length} files changed, ${files.length} mapped, ${changedFns} changed functions, ${(data.links || []).length} calls between files.`, '');

  const flagged = files.flatMap((f) => f.nodes.filter((n) => n.flags.length).map((n) => ({ f, n })));
  if (flagged.length) {
    out.push('## Check first', '');
    for (const { f, n } of flagged) out.push(`- \`${label(n)}\` (${where(f, n)}): ${n.flags.join(', ')}`);
    out.push('');
  }

  if ((data.links || []).length) {
    out.push('## Calls between files', '');
    for (const l of data.links) {
      const a = nodeOf(l.from), b = nodeOf(l.to);
      if (a && a.n && b && b.n) out.push(`- \`${label(a.n)}\` (${where(a.f, a.n)}) → \`${label(b.n)}\` (${where(b.f, b.n)})`);
    }
    out.push('');
  }

  out.push('## Reading order', '', 'Per file, entry points first, then what they call. Indented items are called by the item above them.', '');
  for (const f of files) {
    out.push(`### ${f.file} (${f.status}, ${f.lang})`, '');
    const byId = new Map(f.nodes.map((n) => [n.id, n]));
    const callees = (n) => f.edges.filter((e) => e.from === n.id).map((e) => byId.get(e.to)).filter(Boolean).sort((a, b) => a.start - b.start);
    const callers = new Set(f.edges.map((e) => e.to));
    const roots = f.nodes.filter((n) => !callers.has(n.id)).sort((a, b) => a.tier - b.tier || a.start - b.start);
    const seen = new Set();
    const line = (n, depth) => {
      const bits = [where(f, n)];
      if (n.changed) bits.push(`+${n.added}`); else bits.push('unchanged');
      if (n.kind === 'const') bits.push('constant');
      if (n.flags.length) bits.push(`⚠ ${n.flags.join(', ')}`);
      const out2 = (data.links || []).filter((l) => l.from.file === f.file && l.from.id === n.id).map((l) => nodeOf(l.to)).filter((x) => x && x.n);
      if (out2.length) bits.push(`calls ${out2.map(({ f: g, n: t }) => `\`${label(t)}\` in ${g.file}`).join(', ')}`);
      const in2 = (data.links || []).filter((l) => l.to.file === f.file && l.to.id === n.id).map((l) => nodeOf(l.from)).filter((x) => x && x.n);
      if (in2.length) bits.push(`called from ${in2.map(({ f: g, n: t }) => `\`${label(t)}\` in ${g.file}`).join(', ')}`);
      return `${'  '.repeat(depth)}- \`${label(n)}\` · ${bits.join(' · ')}`;
    };
    const walk = (n, depth) => {
      if (seen.has(n.id)) { out.push(`${'  '.repeat(depth)}- \`${label(n)}\` (see above)`); return; }
      seen.add(n.id);
      out.push(line(n, depth));
      for (const c of callees(n)) walk(c, depth + 1);
    };
    for (const r of roots) walk(r, 0);
    for (const n of f.nodes) if (!seen.has(n.id)) walk(n, 0); // cycles with no root
    out.push('');
  }

  if ((m.notMapped || []).length) {
    out.push('## Not mapped', '');
    for (const x of m.notMapped) out.push(`- ${x.file}: ${x.reason}`);
    out.push('');
  }
  return out.join('\n');
}

module.exports = { toAgentMarkdown };
